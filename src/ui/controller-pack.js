export const packUrl = (kind) => (PACK[kind] ? `/controllers/pack/${PACK[kind].src}` : null);

/** Live diagram: the picture with hotspots (glow on press) and stick rings (follow the sticks). */
export function packSvg(kind) {
  const p = PACK[kind];
  const u = p.w / 400; // one "diagram unit" (the drawn art is 400 wide)
  const hot = Object.entries(p.hot).map(([b, [x, y, r]]) =>
    `<g class="b hot" data-b="${b}"${b === '6' || b === '7' ? ` data-trig="${b}"` : ''}><circle ${b === '6' || b === '7' ? 'class="tfill" opacity="0" ' : ''}cx="${x}" cy="${y}" r="${r}"/></g>`).join('');
  const sticks = Object.entries(p.sticks || {}).map(([s, [x, y, r]]) =>
    `<g data-stick="${s}" data-move="${(7 * u).toFixed(1)}"><circle class="stick-ring" cx="${x}" cy="${y}" r="${r}" stroke-width="${(2.2 * u).toFixed(1)}"/></g>`).join('');
  return `<svg class="pack-art" viewBox="0 0 ${p.w} ${p.h}" xmlns="http://www.w3.org/2000/svg" role="img"><image href="/controllers/pack/${p.src}" width="${p.w}" height="${p.h}"/>${hot}${sticks}</svg>`;
}
